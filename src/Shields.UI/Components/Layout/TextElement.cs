namespace Shields.UI.Components.Layout;

/// <summary>HTML element a <see cref="Text"/> renders as.</summary>
public enum TextElement
{
    /// <summary>Inline <c>span</c>.</summary>
    Span,

    /// <summary>Paragraph (<c>p</c>).</summary>
    P,

    /// <summary>Block <c>div</c>.</summary>
    Div,

    /// <summary>Heading level 2 (<c>h2</c>).</summary>
    H2,

    /// <summary>Heading level 3 (<c>h3</c>).</summary>
    H3,

    /// <summary>Heading level 4 (<c>h4</c>).</summary>
    H4,

    /// <summary>Heading level 5 (<c>h5</c>).</summary>
    H5,

    /// <summary>Heading level 6 (<c>h6</c>).</summary>
    H6,
}
