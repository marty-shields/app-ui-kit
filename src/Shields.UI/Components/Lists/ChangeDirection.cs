namespace Shields.UI.Components.Lists;

public enum ChangeDirection
{
    /// <summary>No change: a muted dash.</summary>
    None,

    /// <summary>An increase: an up arrow in <c>--color-success</c>.</summary>
    Up,

    /// <summary>A decrease: a down arrow in <c>--color-error</c>.</summary>
    Down,
}
